/**
 * Helper: Get keyboards by category
 */
export function getKeyboardsByCategory(category) {
  return keyboards.filter((kb) => kb.category.includes(category));
}

/**
 * Helper: Get a keyboard by ID
 */
export function getKeyboardById(id) {
  return keyboards.find((kb) => kb.id === id);
}

/**
 * Helper: Get keyboards sorted by price (low to high)
 */
export function getKeyboardsSortedByPrice(list = keyboards) {
  return [...list].sort((a, b) => a.price - b.price);
}
